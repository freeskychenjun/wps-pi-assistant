const fs = require("fs");
const path = require("path");
const DIR = path.resolve(__dirname, "..");
const mp = path.join(DIR, "sessions-map.json");
const map = JSON.parse(fs.readFileSync(mp, "utf8"));
const key = path.join(DIR, "test-p6.docx");
const real = path.join(DIR, "sessions", "2026-11-11T15-56-07-384Z_01a1cb52-db58-7025-b409-610cc70526fe.jsonl");
const old = map[key];
const list = ((old && old.list) || []).filter((f) => f !== (old && old.current) && fs.existsSync(f));
if (list.indexOf(real) < 0) list.unshift(real);
map[key] = { current: real, list: list };
fs.writeFileSync(mp, JSON.stringify(map, null, 2), "utf8");
console.log("key  =", key);
console.log("real =", real, "exists:", fs.existsSync(real));
console.log("entry=", JSON.stringify(map[key], null, 1));
